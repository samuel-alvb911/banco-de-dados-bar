DROP VIEW  IF EXISTS vw_venda_total;
DROP TABLE IF EXISTS Item_Venda;
DROP TABLE IF EXISTS Movimentacao_Estoque;
DROP TABLE IF EXISTS Estoque;
DROP TABLE IF EXISTS Venda;
DROP TABLE IF EXISTS Produto;
DROP TABLE IF EXISTS Categoria;
DROP TABLE IF EXISTS Despesa;

-- ---------------------------------------------------------------------
-- TABELAS
-- ---------------------------------------------------------------------

CREATE TABLE Categoria (
    id_categoria  SERIAL        PRIMARY KEY,
    nome          VARCHAR(100)  NOT NULL UNIQUE,
    descricao     TEXT
);

CREATE TABLE Produto (
    id_produto      SERIAL         PRIMARY KEY,
    nome            VARCHAR(100)   NOT NULL UNIQUE,
    descricao       TEXT,
    preco_venda     DECIMAL(10,2)  NOT NULL CHECK (preco_venda >= 0),
    unidade_medida  VARCHAR(20)    NOT NULL,
    id_categoria    INTEGER        NOT NULL,
    CONSTRAINT fk_produto_categoria
        FOREIGN KEY (id_categoria) REFERENCES Categoria (id_categoria)
);

CREATE TABLE Estoque (
    id_estoque        SERIAL   PRIMARY KEY,
    id_produto        INTEGER  NOT NULL UNIQUE,
    quantidade_atual  INTEGER  NOT NULL DEFAULT 0 CHECK (quantidade_atual >= 0),
    estoque_minimo    INTEGER  NOT NULL DEFAULT 0 CHECK (estoque_minimo >= 0),
    CONSTRAINT fk_estoque_produto
        FOREIGN KEY (id_produto) REFERENCES Produto (id_produto)
);

CREATE TABLE Movimentacao_Estoque (
    id_movimentacao    SERIAL        PRIMARY KEY,
    id_produto         INTEGER       NOT NULL,
    tipo_movimentacao  VARCHAR(20)   NOT NULL
        CHECK (tipo_movimentacao IN ('entrada', 'saída')),
    quantidade         INTEGER       NOT NULL CHECK (quantidade > 0),
    data_hora          TIMESTAMP     NOT NULL,
    motivo             VARCHAR(150),
    CONSTRAINT fk_mov_produto
        FOREIGN KEY (id_produto) REFERENCES Produto (id_produto)
);

CREATE TABLE Venda (
    id_venda         SERIAL       PRIMARY KEY,
    data_hora        TIMESTAMP    NOT NULL,
    forma_pagamento  VARCHAR(30)  NOT NULL
);

CREATE TABLE Item_Venda (
    id_item         SERIAL         PRIMARY KEY,
    id_venda        INTEGER        NOT NULL,
    id_produto      INTEGER        NOT NULL,
    quantidade      INTEGER        NOT NULL CHECK (quantidade > 0),
    preco_unitario  DECIMAL(10,2)  NOT NULL CHECK (preco_unitario >= 0),
    CONSTRAINT fk_item_venda
        FOREIGN KEY (id_venda)   REFERENCES Venda (id_venda),
    CONSTRAINT fk_item_produto
        FOREIGN KEY (id_produto) REFERENCES Produto (id_produto)
);

CREATE TABLE Despesa (
    id_despesa         SERIAL         PRIMARY KEY,
    descricao          VARCHAR(150)   NOT NULL,
    valor              DECIMAL(10,2)  NOT NULL CHECK (valor > 0),
    data               DATE           NOT NULL,
    categoria_despesa  VARCHAR(50)    NOT NULL,
    forma_pagamento    VARCHAR(30)    NOT NULL
);

-- ---------------------------------------------------------------------
-- VIEW: valor total de cada venda (substitui o atributo derivado
-- valor_total, removido para atender à 3FN)
-- ---------------------------------------------------------------------

CREATE VIEW vw_venda_total AS
SELECT v.id_venda,
       v.data_hora,
       v.forma_pagamento,
       SUM(i.quantidade * i.preco_unitario) AS valor_total
FROM Venda v
JOIN Item_Venda i ON i.id_venda = v.id_venda
GROUP BY v.id_venda, v.data_hora, v.forma_pagamento;

